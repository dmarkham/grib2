#!/usr/bin/env python3
"""Generate codetables_wmo.go from the eccodes WMO code tables.

    python3 scripts/gen_codetables.py reference/eccodes/definitions/grib2/tables/35

The generated maps only fill codes the hand-written tables in codetables.go
do not have, so existing names never change. Reserved entries are skipped.
"""
import glob
import os
import re
import sys

LINE = re.compile(r"^\s*(\d+)\s+\S+\s+(.*?)\s*$")
UNIT = re.compile(r"^(.*?)\s*\(([^()]*)\)\s*$")


def read(path, with_units=False):
    out = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("#"):
                continue
            m = LINE.match(line)
            if not m:
                continue
            code, desc = int(m.group(1)), m.group(2).strip()
            if not desc or desc.lower().startswith("reserved") or desc == "Missing":
                continue
            unit = None
            if with_units:
                u = UNIT.match(desc)
                if u:
                    desc, unit = u.group(1).strip(), u.group(2).strip()
            out[code] = (desc, unit)
    return out


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(tables):
    w = []
    w.append("// Code generated by scripts/gen_codetables.py from the eccodes WMO code\n")
    w.append("// tables (version %s). DO NOT EDIT.\n\n" % os.path.basename(tables.rstrip("/")))
    w.append("package grib2\n\n")

    def simple(name, typ, table, maxcode):
        rows = read(os.path.join(tables, table))
        w.append("var %s = map[%s]string{\n" % (name, typ))
        for c in sorted(rows):
            if c <= maxcode:
                w.append("\t%d: %s,\n" % (c, q(rows[c][0])))
        w.append("}\n\n")

    simple("wmoDisciplineTable", "uint8", "0.0.table", 255)
    simple("wmoReferenceTimeTable", "uint8", "1.2.table", 255)
    simple("wmoProductionStatusTable", "uint8", "1.3.table", 255)
    simple("wmoDataTypeTable", "uint8", "1.4.table", 255)
    simple("wmoGridDefinitionTemplateTable", "uint16", "3.1.table", 65535)
    simple("wmoProductDefinitionTemplateTable", "uint16", "4.0.table", 65535)
    simple("wmoDataRepresentationTemplateTable", "uint16", "5.0.table", 65535)

    rows = read(os.path.join(tables, "4.5.table"), with_units=True)
    w.append("var wmoSurfaceTypeTable = map[uint8]string{\n")
    for c in sorted(rows):
        if c <= 255:
            w.append("\t%d: %s,\n" % (c, q(rows[c][0])))
    w.append("}\n\n")

    w.append("var wmoParameterCategoryTable = map[uint16]string{\n")
    for path in sorted(glob.glob(os.path.join(tables, "4.1.*.table"))):
        d = os.path.basename(path).split(".")[2]
        if not d.isdigit() or int(d) > 255:
            continue
        for c, (desc, _) in sorted(read(path).items()):
            if c <= 255:
                w.append("\t%d<<8 | %d: %s,\n" % (int(d), c, q(desc)))
    w.append("}\n\n")

    names, units = [], []
    for path in sorted(glob.glob(os.path.join(tables, "4.2.*.*.table"))):
        parts = os.path.basename(path).split(".")
        d, c = parts[2], parts[3]
        if not (d.isdigit() and c.isdigit()) or int(d) > 255 or int(c) > 255:
            continue
        for n, (desc, unit) in sorted(read(path, with_units=True).items()):
            if n > 255:
                continue
            key = "%d<<16 | %d<<8 | %d" % (int(d), int(c), n)
            names.append("\t%s: %s,\n" % (key, q(desc)))
            if unit:
                units.append("\t%s: %s,\n" % (key, q(unit)))
    w.append("var wmoParameterTable = map[uint32]string{\n" + "".join(names) + "}\n\n")
    w.append("var wmoParameterUnitTable = map[uint32]string{\n" + "".join(units) + "}\n")

    with open("codetables_wmo.go", "w", encoding="utf-8") as f:
        f.write("".join(w))


if __name__ == "__main__":
    main(sys.argv[1])
