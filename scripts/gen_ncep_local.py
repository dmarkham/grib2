#!/usr/bin/env python3
"""Generate codetables_ncep.go: the parameters NCEP defines in the part of
Code Table 4.2 reserved for local use (category or number 192-254).

    python3 scripts/gen_ncep_local.py gribtable.dat > codetables_ncep.go

gribtable.dat is wgrib2's NCEP table, which wgrib2 builds from NCEP's own
GRIB2 documentation (https://www.nco.ncep.noaa.gov/pmb/docs/grib2/grib2_doc/):

    https://raw.githubusercontent.com/NOAA-EMC/wgrib2/46676e16bcb800044da412abe1135927758aed24/src/gribtables/ncep/gribtable.dat

Its lines are
    {discipline, master, 0, 255, centre, local table version, category, number, "abbreviation", "name", "unit"},
with master = 0 and centre = 7 for NCEP's local parameters; the other lines
are WMO parameters, which codetables.go and codetables_wmo.go already have.
Units are kept in wgrib2's notation ("kg/m^2", "-" for none).
"""
import re
import sys

LINE = re.compile(r'^\{(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)"\},?$')
NCEP = 7


def main():
    rows = {}
    for line in open(sys.argv[1], encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        m = LINE.match(line)
        if not m:
            sys.exit("cannot parse: " + line)
        disc, master, _, _, centre, _, cat, num = map(int, m.groups()[:8])
        if master != 0 or centre != NCEP:
            continue
        if cat == 255 or num == 255:
            continue  # 255 is "missing", not a parameter ("Image data")
        if cat < 192 and num < 192:
            sys.exit("not a local-use code: " + line)
        key = (disc, cat, num)
        if key in rows:
            sys.exit("defined twice: " + line)
        rows[key] = (m.group(10).strip(), m.group(11).strip())

    out = ["// Code generated by scripts/gen_ncep_local.py from wgrib2's NCEP table",
           "// (NOAA-EMC/wgrib2 src/gribtables/ncep/gribtable.dat). DO NOT EDIT.",
           "", "package grib2", "",
           "// ncepLocalParameterTable names the parameters NCEP (centre 7) defines in",
           "// the part of Code Table 4.2 reserved for local use: category or number",
           "// 192 to 254. Key: (discipline << 16) | (category << 8) | number.",
           "var ncepLocalParameterTable = map[uint32]string{"]
    for (d, c, n), (name, _) in sorted(rows.items()):
        out.append("\t%d<<16 | %d<<8 | %d: %s," % (d, c, n, quote(name)))
    out += ["}", "",
            "// ncepLocalParameterUnitTable holds their units, in wgrib2's notation.",
            "var ncepLocalParameterUnitTable = map[uint32]string{"]
    for (d, c, n), (_, unit) in sorted(rows.items()):
        out.append("\t%d<<16 | %d<<8 | %d: %s," % (d, c, n, quote(unit)))
    out.append("}")
    print("\n".join(out))


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
